// Generate symbolic UI-string and bundled-vector accessors. Committed output is checked in CI.
import { readFileSync, writeFileSync } from 'node:fs';
const strings = JSON.parse(readFileSync(new URL('../src/strings.json', import.meta.url), 'utf8'));
const assets = JSON.parse(readFileSync(new URL('../src/assets.json', import.meta.url), 'utf8'));
const keys = Object.keys(strings.en);
for (const [locale, values] of Object.entries(strings)) {
  if (keys.some((key) => typeof values[key] !== 'string') || Object.keys(values).length !== keys.length) {
    throw new Error(`Incomplete translation catalog: ${locale}`);
  }
}
const imports = Object.entries(assets).map(([key, path]) => `import ${key} from ${JSON.stringify('../' + path.replace(/^\.\//, '') + '?raw')};`);
const code = `// Generated by scripts/generate-resources.mjs. Do not edit.\n${imports.join('\n')}\n` +
 `const strings = ${JSON.stringify(strings)};\n` +
 `export const res = {\n vectors: {${Object.keys(assets).map((key) => `${key}: () => ${key}`).join(',')}},\n` +
 ` str(locale) {\n const tag = locale.toLowerCase();\n` +
 ` const key = Object.keys(strings).find((key) => key.toLowerCase() === tag) ?? Object.keys(strings).find((key) => tag.startsWith(key.toLowerCase() + '-')) ?? (tag.startsWith('zh-hans') ? 'zh-CN' : undefined);\n` +
 ` if (!key) throw new Error('App Fair UI translations are missing for ' + locale);\n const values = strings[key];\n` +
 ` return {${keys.map((key) => `${key}: () => values.${key}`).join(',')}};\n }\n};\n`;
const out = new URL('../src/generated/resources.mjs', import.meta.url);
if (process.argv.includes('--check')) {
 if (readFileSync(out, 'utf8') !== code) throw new Error('Regenerate App Fair resources with npm run resources');
} else writeFileSync(out, code);
